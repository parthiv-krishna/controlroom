//! SSH keys: the owner's controlroom key and additional keys.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::ids::{KeyId, UnixMillis};

/// The owner's controlroom key, used for every machine without a `key_id`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct ControlroomKey {
    /// e.g. `"SHA256:..."`.
    pub fingerprint: String,
    /// The OpenSSH public key line.
    pub public_key: String,
    /// When the key was generated.
    pub created_at: UnixMillis,
    /// A command that appends the public key to `~/.ssh/authorized_keys`, ready to copy.
    pub install_command: String,
    /// Machines still on the previous key after a rotation (unreachable during it).
    pub retiring_machines: u32,
}

/// An additional (imported or generated) key.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct AdditionalKey {
    /// The key.
    pub id: KeyId,
    /// User-chosen label.
    pub name: String,
    /// Imported (`true`) or generated by controlroom (`false`).
    pub imported: bool,
    /// e.g. `"SHA256:..."`.
    pub fingerprint: String,
    /// The OpenSSH public key line.
    pub public_key: String,
    /// When it was added.
    pub created_at: UnixMillis,
}

/// Result of `keys.list`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct KeysListResult {
    /// The controlroom key.
    pub controlroom: ControlroomKey,
    /// Additional keys.
    pub additional: Vec<AdditionalKey>,
}

/// Result of `keys.rotate`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct KeysRotateResult {
    /// The new controlroom key.
    pub key: ControlroomKey,
    /// Machines migrated to the new key now.
    pub migrated: u32,
    /// Unreachable machines that migrate when they reconnect.
    pub pending: u32,
}

/// Params of `keys.generate`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct KeysGenerateParams {
    /// Label for the new key.
    pub name: String,
}

/// Params of `keys.import`. The passphrase decrypts the key once and is discarded.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct KeysImportParams {
    /// Label for the key.
    pub name: String,
    /// The OpenSSH private key.
    pub private_key: String,
    /// Its passphrase, if encrypted.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub passphrase: Option<String>,
}

/// Params of `keys.delete`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct KeysDeleteParams {
    /// The additional key; `key_in_use` while machines use it.
    pub key_id: KeyId,
}
