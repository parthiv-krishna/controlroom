//! TypeScript generation, in two sets (both read-only for their users):
//!
//! - [`generate`]: the daemon and UI APIs, for `web/src/lib/protocol/`;
//! - [`generate_agent`]: the agent API, for `extensions/pi/src/protocol/`.
//!
//! Output of each set, all deterministic:
//! - one file per exported type, produced by ts-rs (`SessionSummary.ts`, ...);
//! - `DaemonMethods.ts` and `UiMethods.ts` (`AgentMethods.ts`): maps from method name to `{params, result}` and from
//!   notification name to params, for typed `call` / `on` helpers;
//! - `versions.ts`: the protocol version constants (the only runtime values);
//! - `index.ts`: re-exports everything.
//!
//! Regenerate the checked-in copy with [`REGENERATE_COMMAND`]. Without the variable, that test
//! fails when the checked-in files differ from what the Rust types generate.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::io;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS, TypeVisitor};

use crate::agent::{AgentNotification, AgentRequest};
use crate::daemon::{DaemonNotification, DaemonRequest};
use crate::error::RpcError;
use crate::jsonrpc::{Method, NotificationMethod, RpcNotification, RpcRequest, RpcResponse};
use crate::ui::{UiNotification, UiRequest};
use crate::version::{
    AGENT_PROTOCOL_VERSION, DAEMON_PROTOCOL_VERSION, ProtocolVersion, UI_PROTOCOL_VERSION,
};

/// The command that regenerates the checked-in TypeScript.
pub const REGENERATE_COMMAND: &str =
    "CONTROLROOM_UPDATE_TS=1 cargo test -p controlroom-protocol --test typescript";

/// Where each set is checked in, relative to the repository root.
pub const WEB_DIR: &str = "web/src/lib/protocol";
/// See [`WEB_DIR`].
pub const AGENT_DIR: &str = "extensions/pi/src/protocol";

const GENERATED_NOTE: &str =
    "// This file was generated by controlroom-protocol. Do not edit this file manually.\n";

/// Files written next to the per-type files; a type with one of these names would collide.
const SPECIAL_FILES: [&str; 5] = [
    "DaemonMethods.ts",
    "UiMethods.ts",
    "AgentMethods.ts",
    "versions.ts",
    "index.ts",
];

/// Errors from TypeScript generation.
#[derive(Debug, thiserror::Error)]
pub enum TsExportError {
    /// ts-rs failed to render a type.
    #[error("ts-rs export failed: {0}")]
    TsRs(#[from] ts_rs::ExportError),
    /// Two different Rust types map to the same TypeScript file.
    #[error("two Rust types export to {0}; rename one")]
    Collision(PathBuf),
    /// Writing the output failed.
    #[error("writing TypeScript failed: {0}")]
    Io(#[from] io::Error),
}

/// One method or notification, for the TypeScript method maps.
pub(crate) struct MethodSpec {
    name: &'static str,
    docs: Vec<&'static str>,
    params: TypeRef,
    /// `None` for notifications.
    result: Option<TypeRef>,
    collect: fn(&mut Collector<'_>),
}

/// How a method map refers to a type: its TypeScript name and the files to import it from.
struct TypeRef {
    ts_name: String,
    imports: BTreeMap<String, PathBuf>,
}

impl TypeRef {
    fn of<T: TS + 'static>(cfg: &Config) -> TypeRef {
        struct Names<'a> {
            imports: &'a mut BTreeMap<String, PathBuf>,
            cfg: &'a Config,
        }
        impl TypeVisitor for Names<'_> {
            fn visit<U: TS + 'static + ?Sized>(&mut self) {
                if let Some(path) = U::output_path() {
                    self.imports.insert(U::ident(self.cfg), path);
                }
                U::visit_generics(self);
            }
        }
        let mut imports = BTreeMap::new();
        Names {
            imports: &mut imports,
            cfg,
        }
        .visit::<T>();
        TypeRef {
            ts_name: T::name(cfg),
            imports,
        }
    }
}

impl MethodSpec {
    pub(crate) fn request<M: Method>(docs: &[&'static str]) -> MethodSpec {
        let cfg = config();
        MethodSpec {
            name: M::NAME,
            docs: docs.to_vec(),
            params: TypeRef::of::<M::Params>(&cfg),
            result: Some(TypeRef::of::<M::Result>(&cfg)),
            collect: |c| {
                c.visit::<M::Params>();
                c.visit::<M::Result>();
            },
        }
    }

    pub(crate) fn notification<N: NotificationMethod>(docs: &[&'static str]) -> MethodSpec {
        let cfg = config();
        MethodSpec {
            name: N::NAME,
            docs: docs.to_vec(),
            params: TypeRef::of::<N::Params>(&cfg),
            result: None,
            collect: |c| c.visit::<N::Params>(),
        }
    }
}

fn config() -> Config {
    // Seqs, revs, token counts and unix ms stay far below 2^53, so plain numbers are safe.
    Config::new().with_large_int("number")
}

/// Walks types and their dependencies, rendering each exportable type once.
struct Collector<'a> {
    cfg: &'a Config,
    files: BTreeMap<PathBuf, (TypeId, String)>,
    seen: HashSet<TypeId>,
    error: Option<TsExportError>,
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if let Some(path) = T::output_path() {
            let owner = TypeId::of::<T::WithoutGenerics>();
            match self.files.get(&path) {
                Some((existing, _)) if *existing != owner => {
                    self.error = Some(TsExportError::Collision(path));
                    return;
                }
                Some(_) => {}
                None => match T::export_to_string(self.cfg) {
                    Ok(source) => {
                        self.files.insert(path, (owner, source));
                    }
                    Err(err) => {
                        self.error = Some(err.into());
                        return;
                    }
                },
            }
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

fn module_of(path: &Path) -> String {
    path.to_string_lossy().trim_end_matches(".ts").to_owned()
}

fn write_doc(out: &mut String, indent: &str, lines: &[&str]) {
    if lines.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in lines {
        match line.strip_prefix(' ').unwrap_or(line) {
            "" => {
                let _ = writeln!(out, "{indent} *");
            }
            line => {
                let _ = writeln!(out, "{indent} * {line}");
            }
        }
    }
    let _ = writeln!(out, "{indent} */");
}

fn method_map(api: &str, methods: &[MethodSpec], notifications: &[MethodSpec]) -> String {
    let mut imports: BTreeMap<String, PathBuf> = BTreeMap::new();
    for spec in methods.iter().chain(notifications) {
        imports.extend(spec.params.imports.clone());
        if let Some(result) = &spec.result {
            imports.extend(result.imports.clone());
        }
    }

    let mut out = String::from(GENERATED_NOTE);
    for (ident, path) in &imports {
        let _ = writeln!(
            out,
            "import type {{ {ident} }} from \"./{}\";",
            module_of(path)
        );
    }
    out.push('\n');

    write_doc(
        &mut out,
        "",
        &[&format!(
            "Every {api} API request method by name, with its params and result types."
        )],
    );
    let _ = writeln!(out, "export type {api}Methods = {{");
    for spec in methods {
        write_doc(&mut out, "  ", &spec.docs);
        let result = spec.result.as_ref().map_or("never", |r| r.ts_name.as_str());
        let _ = writeln!(
            out,
            "  \"{}\": {{ params: {}, result: {} }},",
            spec.name, spec.params.ts_name, result
        );
    }
    out.push_str("};\n\n");
    write_doc(
        &mut out,
        "",
        &[&format!("A {api} API request method name.")],
    );
    let _ = writeln!(out, "export type {api}Method = keyof {api}Methods;\n");

    write_doc(
        &mut out,
        "",
        &[&format!(
            "Every {api} API notification by name, with its params type."
        )],
    );
    let _ = writeln!(out, "export type {api}Notifications = {{");
    for spec in notifications {
        write_doc(&mut out, "  ", &spec.docs);
        let _ = writeln!(out, "  \"{}\": {},", spec.name, spec.params.ts_name);
    }
    out.push_str("};\n\n");
    write_doc(&mut out, "", &[&format!("A {api} API notification name.")]);
    let _ = writeln!(
        out,
        "export type {api}NotificationName = keyof {api}Notifications;"
    );
    out
}

fn versions_file(versions: &[(&str, &str, ProtocolVersion)]) -> String {
    let mut out =
        format!("{GENERATED_NOTE}import type {{ ProtocolVersion }} from \"./ProtocolVersion\";\n");
    for (name, doc, v) in versions {
        let _ = write!(
            out,
            "\n/**\n * {doc} Peers are compatible iff their majors match.\n */\n\
             export const {name}: ProtocolVersion = {{ major: {}, minor: {} }};\n",
            v.major, v.minor
        );
    }
    out
}

fn index_file(files: &BTreeMap<PathBuf, String>) -> String {
    let mut out = String::from(GENERATED_NOTE);
    let _ = writeln!(out, "// Regenerate with: {REGENERATE_COMMAND}\n");
    for path in files.keys() {
        let module = module_of(path);
        if module == "versions" {
            let _ = writeln!(out, "export * from \"./{module}\";");
        } else {
            let _ = writeln!(out, "export type * from \"./{module}\";");
        }
    }
    out
}

/// One API of a set: its name prefix and method tables.
struct Api {
    name: &'static str,
    methods: Vec<MethodSpec>,
    notifications: Vec<MethodSpec>,
}

/// Generates one set: every type the APIs reach, a method map per API, `versions.ts` and
/// `index.ts`.
fn generate_set(
    apis: &[Api],
    versions: &[(&str, &str, ProtocolVersion)],
) -> Result<BTreeMap<PathBuf, String>, TsExportError> {
    let cfg = config();
    let mut collector = Collector {
        cfg: &cfg,
        files: BTreeMap::new(),
        seen: HashSet::new(),
        error: None,
    };
    collector.visit::<RpcRequest<ts_rs::Dummy>>();
    collector.visit::<RpcResponse<ts_rs::Dummy>>();
    collector.visit::<RpcNotification<ts_rs::Dummy>>();
    collector.visit::<RpcError>();
    collector.visit::<ProtocolVersion>();
    for api in apis {
        for spec in api.methods.iter().chain(&api.notifications) {
            (spec.collect)(&mut collector);
        }
    }
    if let Some(err) = collector.error {
        return Err(err);
    }

    let mut files: BTreeMap<PathBuf, String> = collector
        .files
        .into_iter()
        .map(|(path, (_, source))| (path, source))
        .collect();
    if let Some(name) = SPECIAL_FILES
        .iter()
        .find(|name| files.contains_key(Path::new(name)))
    {
        return Err(TsExportError::Collision(PathBuf::from(name)));
    }
    for api in apis {
        files.insert(
            format!("{}Methods.ts", api.name).into(),
            method_map(api.name, &api.methods, &api.notifications),
        );
    }
    files.insert("versions.ts".into(), versions_file(versions));
    let index = index_file(&files);
    files.insert("index.ts".into(), index);
    Ok(files)
}

/// Generates the daemon and UI API set ([`WEB_DIR`]), keyed by path relative to it.
pub fn generate() -> Result<BTreeMap<PathBuf, String>, TsExportError> {
    generate_set(
        &[
            Api {
                name: "Daemon",
                methods: DaemonRequest::specs(),
                notifications: DaemonNotification::specs(),
            },
            Api {
                name: "Ui",
                methods: UiRequest::specs(),
                notifications: UiNotification::specs(),
            },
        ],
        &[
            (
                "DAEMON_PROTOCOL_VERSION",
                "The daemon API version.",
                DAEMON_PROTOCOL_VERSION,
            ),
            (
                "UI_PROTOCOL_VERSION",
                "The UI API version, sent in the UI `hello`.",
                UI_PROTOCOL_VERSION,
            ),
        ],
    )
}

/// Generates the agent API set ([`AGENT_DIR`]), keyed by path relative to it.
pub fn generate_agent() -> Result<BTreeMap<PathBuf, String>, TsExportError> {
    generate_set(
        &[Api {
            name: "Agent",
            methods: AgentRequest::specs(),
            notifications: AgentNotification::specs(),
        }],
        &[(
            "AGENT_PROTOCOL_VERSION",
            "The agent API version, sent in the agent `hello`.",
            AGENT_PROTOCOL_VERSION,
        )],
    )
}

/// Replaces the `.ts` files in `dir` with `files`. Other files are left alone.
pub fn write_to(dir: &Path, files: BTreeMap<PathBuf, String>) -> Result<(), TsExportError> {
    if dir.exists() {
        for existing in list_ts_files(dir)? {
            std::fs::remove_file(dir.join(existing))?;
        }
    }
    std::fs::create_dir_all(dir)?;
    for (path, source) in files {
        std::fs::write(dir.join(path), source)?;
    }
    Ok(())
}

/// Lists the `.ts` files directly in `dir`, sorted.
pub fn list_ts_files(dir: &Path) -> io::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_file() && path.extension().is_some_and(|ext| ext == "ts") {
            out.push(path.strip_prefix(dir).unwrap_or(&path).to_path_buf());
        }
    }
    out.sort();
    Ok(out)
}
