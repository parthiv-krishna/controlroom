//! The client store schema. Edited in place until the first release (spec §2 "Compatibility"):
//! bump [`VERSION`] on every change; an existing database with another version is refused.
//!
//! Every table except `owners` and `installation` carries a non-null `owner_id`. Child tables
//! reference their parents through composite `(id, owner_id)` keys, so a row can never point at
//! another owner's row. Task links and contact grants deliberately have no foreign key to
//! machines or sessions: they survive session purges and machine removal and render as
//! "missing session". Sessions are global (the agent daemon's), so they are named by id alone.

use rusqlite::Connection;

use super::{StoreError, StoreResult};

/// The schema version, kept in `PRAGMA user_version`.
pub(super) const VERSION: u32 = 5;

const SCHEMA: &str = r#"
CREATE TABLE installation (
    controller_id  TEXT NOT NULL
) STRICT;

CREATE TABLE owners (
    id          TEXT PRIMARY KEY NOT NULL,
    created_at  INTEGER NOT NULL
) STRICT;

CREATE TABLE keys (
    id                  TEXT PRIMARY KEY NOT NULL,
    owner_id            TEXT NOT NULL REFERENCES owners(id),
    name                TEXT NOT NULL,
    kind                TEXT NOT NULL CHECK (kind IN ('controlroom', 'additional')),
    -- Additional keys: generated by controlroom (1) or imported (0).
    generated           INTEGER NOT NULL,
    public_key          TEXT NOT NULL,
    fingerprint         TEXT NOT NULL,
    sealed_private_key  BLOB NOT NULL,
    created_at          INTEGER NOT NULL,
    -- Set on a controlroom key replaced by a rotation; deleted once no machine uses it.
    retired_at          INTEGER,
    UNIQUE (id, owner_id)
) STRICT;
CREATE INDEX keys_owner ON keys (owner_id, kind);

CREATE TABLE machines (
    id               TEXT PRIMARY KEY NOT NULL,
    owner_id         TEXT NOT NULL REFERENCES owners(id),
    name             TEXT NOT NULL,
    host             TEXT NOT NULL,
    port             INTEGER NOT NULL CHECK (port BETWEEN 1 AND 65535),
    username         TEXT NOT NULL,
    -- An additional key; NULL means the owner's controlroom key.
    key_id           TEXT,
    -- For machines on the controlroom key: which controlroom key (current or retiring) is
    -- installed on the host. No foreign key: a retiring key is deleted once unreferenced.
    auth_key_id      TEXT,
    -- The pinned host key (OpenSSH format); NULL until confirmed.
    host_key         TEXT,
    auto_upgrade     INTEGER NOT NULL DEFAULT 1 CHECK (auto_upgrade IN (0, 1)),
    -- How long agents' tool calls wait for this machine while it is unreachable (seconds).
    grace_s          INTEGER NOT NULL DEFAULT 600 CHECK (grace_s >= 0),
    daemon_id        TEXT,
    home             TEXT,
    arch             TEXT,
    version          TEXT,
    -- The daemon's `hello` capabilities (JSON array of strings).
    capabilities     TEXT NOT NULL DEFAULT '[]',
    last_seen        INTEGER,
    -- The latest doctor report (protocol JSON).
    doctor           TEXT,
    created_at       INTEGER NOT NULL,
    UNIQUE (id, owner_id),
    UNIQUE (owner_id, name),
    UNIQUE (owner_id, host, port, username),
    FOREIGN KEY (key_id, owner_id) REFERENCES keys (id, owner_id) ON DELETE RESTRICT
) STRICT;

CREATE TABLE projects (
    id                 TEXT PRIMARY KEY NOT NULL,
    owner_id           TEXT NOT NULL REFERENCES owners(id),
    name               TEXT NOT NULL,
    color              TEXT NOT NULL,
    created_at         INTEGER NOT NULL,
    UNIQUE (id, owner_id)
) STRICT;

CREATE TABLE tasks (
    id          TEXT PRIMARY KEY NOT NULL,
    owner_id    TEXT NOT NULL REFERENCES owners(id),
    title       TEXT NOT NULL,
    status      TEXT NOT NULL,
    position    REAL NOT NULL,
    priority    TEXT NOT NULL,
    notes       TEXT NOT NULL,
    created_at  INTEGER NOT NULL,
    updated_at  INTEGER NOT NULL,
    UNIQUE (id, owner_id)
) STRICT;
CREATE INDEX tasks_owner ON tasks (owner_id, status, position);

-- One row per checklist entry, so editing one entry touches only its row.
CREATE TABLE task_checklist (
    item_id   TEXT PRIMARY KEY NOT NULL,
    owner_id  TEXT NOT NULL REFERENCES owners(id),
    task_id   TEXT NOT NULL,
    position  REAL NOT NULL,
    text      TEXT NOT NULL,
    done      INTEGER NOT NULL CHECK (done IN (0, 1)),
    FOREIGN KEY (task_id, owner_id) REFERENCES tasks (id, owner_id) ON DELETE CASCADE
) STRICT;
CREATE INDEX task_checklist_task ON task_checklist (owner_id, task_id, position);

CREATE TABLE task_projects (
    owner_id    TEXT NOT NULL REFERENCES owners(id),
    task_id     TEXT NOT NULL,
    project_id  TEXT NOT NULL,
    position    INTEGER NOT NULL,
    PRIMARY KEY (task_id, project_id),
    FOREIGN KEY (task_id, owner_id) REFERENCES tasks (id, owner_id) ON DELETE CASCADE,
    FOREIGN KEY (project_id, owner_id) REFERENCES projects (id, owner_id) ON DELETE CASCADE
) STRICT;
CREATE INDEX task_projects_project ON task_projects (owner_id, project_id);

CREATE TABLE task_links (
    owner_id    TEXT NOT NULL REFERENCES owners(id),
    task_id     TEXT NOT NULL,
    session_id  TEXT NOT NULL,
    created_at  INTEGER NOT NULL,
    PRIMARY KEY (task_id, session_id),
    FOREIGN KEY (task_id, owner_id) REFERENCES tasks (id, owner_id) ON DELETE CASCADE
) STRICT;
CREATE INDEX task_links_session ON task_links (owner_id, session_id);

CREATE TABLE grants (
    id            TEXT PRIMARY KEY NOT NULL,
    owner_id      TEXT NOT NULL REFERENCES owners(id),
    from_session  TEXT NOT NULL,
    to_session    TEXT NOT NULL,
    scope         TEXT NOT NULL,
    granted_at    INTEGER NOT NULL,
    by_device     TEXT,
    by_label      TEXT
) STRICT;
CREATE INDEX grants_owner ON grants (owner_id);

CREATE TABLE devices (
    owner_id    TEXT NOT NULL REFERENCES owners(id),
    device_id   TEXT NOT NULL,
    label       TEXT NOT NULL,
    created_at  INTEGER NOT NULL,
    last_seen   INTEGER NOT NULL,
    PRIMARY KEY (owner_id, device_id)
) STRICT;

-- Login sessions of the web shell. `token_hash` is the SHA-256 of the cookie value, so a copied
-- database yields no usable cookies.
CREATE TABLE auth_sessions (
    token_hash    TEXT PRIMARY KEY NOT NULL,
    owner_id      TEXT NOT NULL REFERENCES owners(id),
    mode          TEXT NOT NULL,
    subject       TEXT NOT NULL,
    groups        TEXT NOT NULL,
    name          TEXT,
    email         TEXT,
    device_id     TEXT,
    csrf_token    TEXT NOT NULL,
    created_at    INTEGER NOT NULL,
    last_seen_at  INTEGER NOT NULL,
    expires_at    INTEGER NOT NULL
) STRICT;
CREATE INDEX auth_sessions_owner ON auth_sessions (owner_id, device_id);
CREATE INDEX auth_sessions_expiry ON auth_sessions (expires_at);

CREATE TABLE push_subscriptions (
    owner_id         TEXT NOT NULL,
    device_id        TEXT NOT NULL,
    endpoint         TEXT NOT NULL,
    p256dh           TEXT NOT NULL,
    auth             TEXT NOT NULL,
    created_at       INTEGER NOT NULL,
    last_success_at  INTEGER,
    PRIMARY KEY (owner_id, device_id),
    FOREIGN KEY (owner_id, device_id) REFERENCES devices (owner_id, device_id) ON DELETE CASCADE
) STRICT;

-- Dedup log: at most one push per device per (session, attention event). Pruned by age.
CREATE TABLE push_deliveries (
    owner_id    TEXT NOT NULL,
    device_id   TEXT NOT NULL,
    session_id  TEXT NOT NULL,
    event_key   TEXT NOT NULL,
    sent_at     INTEGER NOT NULL,
    PRIMARY KEY (owner_id, device_id, session_id, event_key),
    FOREIGN KEY (owner_id, device_id) REFERENCES devices (owner_id, device_id) ON DELETE CASCADE
) STRICT;
CREATE INDEX push_deliveries_age ON push_deliveries (sent_at);

CREATE TABLE schedules (
    id           TEXT PRIMARY KEY NOT NULL,
    owner_id     TEXT NOT NULL REFERENCES owners(id),
    session_id   TEXT NOT NULL,
    name         TEXT NOT NULL,
    spec         TEXT NOT NULL,
    timezone     TEXT NOT NULL,
    message      TEXT NOT NULL,
    enabled      INTEGER NOT NULL CHECK (enabled IN (0, 1)),
    if_busy      TEXT NOT NULL,
    missed       TEXT NOT NULL,
    next_run     INTEGER,
    pending_run  INTEGER,
    recent_runs  TEXT NOT NULL,
    created_at   INTEGER NOT NULL
) STRICT;
CREATE INDEX schedules_owner ON schedules (owner_id);

-- Sandbox defaults of one machine or project (Settings > Sandbox).
CREATE TABLE sandbox_profiles (
    owner_id    TEXT NOT NULL REFERENCES owners(id),
    scope_kind  TEXT NOT NULL CHECK (scope_kind IN ('machine', 'project')),
    scope_id    TEXT NOT NULL,
    level       TEXT,
    grants      TEXT NOT NULL,
    domains     TEXT NOT NULL,
    mediated    TEXT NOT NULL,
    PRIMARY KEY (owner_id, scope_kind, scope_id)
) STRICT;

-- Per-owner UI and notification preferences (JSON values).
CREATE TABLE prefs (
    owner_id  TEXT NOT NULL REFERENCES owners(id),
    key       TEXT NOT NULL,
    value     TEXT NOT NULL,
    PRIMARY KEY (owner_id, key)
) STRICT;
"#;

/// Creates the schema in an empty database, or checks an existing one's version.
pub(super) fn apply(conn: &Connection) -> StoreResult<()> {
    let found: u32 = conn.pragma_query_value(None, "user_version", |row| row.get(0))?;
    if found == VERSION {
        return Ok(());
    }
    let empty: bool = conn.query_row(
        "SELECT NOT EXISTS (SELECT 1 FROM sqlite_master WHERE type = 'table')",
        [],
        |row| row.get(0),
    )?;
    if found != 0 || !empty {
        return Err(StoreError::SchemaMismatch {
            found,
            expected: VERSION,
        });
    }
    conn.execute_batch(&format!(
        "BEGIN; {SCHEMA} PRAGMA user_version = {VERSION}; COMMIT;"
    ))?;
    Ok(())
}
