//! SSH keys, stored as opaque sealed blobs. Sealing binds the key id (client-core's `seal` uses
//! it as associated data), so callers pick the id before sealing ([`KeyId::generate`]).

use controlroom_protocol::UnixMillis;
use controlroom_protocol::ids::KeyId;
use rusqlite::OptionalExtension;

use super::{OwnerId, Store, StoreError, StoreResult, parsed_col};

/// What a key is for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyKind {
    /// The owner's controlroom key (one active, rotatable).
    Controlroom,
    /// An additional key, chosen per machine.
    Additional,
}

impl KeyKind {
    fn as_str(self) -> &'static str {
        match self {
            KeyKind::Controlroom => "controlroom",
            KeyKind::Additional => "additional",
        }
    }

    fn parse(value: &str) -> StoreResult<Self> {
        match value {
            "controlroom" => Ok(KeyKind::Controlroom),
            "additional" => Ok(KeyKind::Additional),
            other => Err(StoreError::InvalidValue {
                column: "keys.kind",
                value: other.to_owned(),
            }),
        }
    }
}

/// A stored key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyRow {
    /// The key.
    pub id: KeyId,
    /// User-chosen label.
    pub name: String,
    /// What it is for.
    pub kind: KeyKind,
    /// Generated by controlroom (rather than imported).
    pub generated: bool,
    /// The OpenSSH public key line.
    pub public_key: String,
    /// `SHA256:...`.
    pub fingerprint: String,
    /// The sealed private key.
    pub sealed_private_key: Vec<u8>,
    /// When it was stored.
    pub created_at: UnixMillis,
    /// Set on a controlroom key a rotation replaced.
    pub retired_at: Option<UnixMillis>,
}

/// A key to store.
#[derive(Debug, Clone)]
pub struct NewKey {
    /// The id the private key was sealed for.
    pub id: KeyId,
    /// Label.
    pub name: String,
    /// What it is for.
    pub kind: KeyKind,
    /// Generated by controlroom.
    pub generated: bool,
    /// The OpenSSH public key line.
    pub public_key: String,
    /// `SHA256:...`.
    pub fingerprint: String,
    /// The sealed private key.
    pub sealed_private_key: Vec<u8>,
}

/// Owner-scoped key operations.
pub struct Keys<'a> {
    store: &'a Store,
    owner: &'a OwnerId,
}

const COLUMNS: &str = "id, name, kind, generated, public_key, fingerprint, sealed_private_key, \
                       created_at, retired_at";

type RawKey = (
    KeyId,
    String,
    String,
    bool,
    String,
    String,
    Vec<u8>,
    i64,
    Option<i64>,
);

fn raw(row: &rusqlite::Row<'_>) -> rusqlite::Result<RawKey> {
    Ok((
        parsed_col(row, 0)?,
        row.get(1)?,
        row.get(2)?,
        row.get(3)?,
        row.get(4)?,
        row.get(5)?,
        row.get(6)?,
        row.get(7)?,
        row.get(8)?,
    ))
}

fn from_raw(r: RawKey) -> StoreResult<KeyRow> {
    Ok(KeyRow {
        id: r.0,
        name: r.1,
        kind: KeyKind::parse(&r.2)?,
        generated: r.3,
        public_key: r.4,
        fingerprint: r.5,
        sealed_private_key: r.6,
        created_at: UnixMillis(r.7),
        retired_at: r.8.map(UnixMillis),
    })
}

fn insert(conn: &rusqlite::Connection, owner: &OwnerId, key: &NewKey, now: i64) -> StoreResult<()> {
    conn.execute(
        "INSERT INTO keys (id, owner_id, name, kind, generated, public_key, fingerprint,
                           sealed_private_key, created_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?9)",
        rusqlite::params![
            key.id.to_string(),
            owner.as_str(),
            key.name,
            key.kind.as_str(),
            key.generated,
            key.public_key,
            key.fingerprint,
            key.sealed_private_key,
            now
        ],
    )?;
    Ok(())
}

impl<'a> Keys<'a> {
    pub(super) fn new(store: &'a Store, owner: &'a OwnerId) -> Self {
        Self { store, owner }
    }

    /// Stores a key.
    pub fn insert(&self, key: NewKey) -> StoreResult<KeyRow> {
        insert(&self.store.lock(), self.owner, &key, UnixMillis::now().0)?;
        self.get(key.id)?
            .ok_or_else(|| StoreError::Conflict("the key vanished".into()))
    }

    /// A key by id.
    pub fn get(&self, id: KeyId) -> StoreResult<Option<KeyRow>> {
        let raw = self
            .store
            .lock()
            .query_row(
                &format!("SELECT {COLUMNS} FROM keys WHERE owner_id = ?1 AND id = ?2"),
                (self.owner.as_str(), id.to_string()),
                raw,
            )
            .optional()?;
        raw.map(from_raw).transpose()
    }

    /// Every key, oldest first.
    pub fn list(&self) -> StoreResult<Vec<KeyRow>> {
        let conn = self.store.lock();
        let mut stmt = conn.prepare(&format!(
            "SELECT {COLUMNS} FROM keys WHERE owner_id = ?1 ORDER BY created_at, id"
        ))?;
        let rows = stmt
            .query_map([self.owner.as_str()], raw)?
            .collect::<Result<Vec<_>, _>>()?;
        rows.into_iter().map(from_raw).collect()
    }

    /// The active (not retired) controlroom key.
    pub fn controlroom(&self) -> StoreResult<Option<KeyRow>> {
        let raw = self
            .store
            .lock()
            .query_row(
                &format!(
                    "SELECT {COLUMNS} FROM keys WHERE owner_id = ?1 AND kind = 'controlroom'
                     AND retired_at IS NULL ORDER BY created_at DESC, id DESC LIMIT 1"
                ),
                [self.owner.as_str()],
                raw,
            )
            .optional()?;
        raw.map(from_raw).transpose()
    }

    /// Replaces the controlroom key in one transaction: machines on the controlroom key that
    /// never recorded theirs are pinned to the old key, the new key is stored and the old one
    /// retired. A machine added concurrently with the old key stays on it (retiring), and the
    /// old key is only deleted once no machine references it ([`Self::prune_retired`]).
    pub fn rotate_controlroom(&self, old: KeyId, new: NewKey) -> StoreResult<()> {
        let now = UnixMillis::now().0;
        self.store.transaction(|tx| {
            tx.execute(
                "UPDATE machines SET auth_key_id = ?2
                 WHERE owner_id = ?1 AND key_id IS NULL AND auth_key_id IS NULL",
                (self.owner.as_str(), old.to_string()),
            )?;
            insert(tx, self.owner, &new, now)?;
            tx.execute(
                "UPDATE keys SET retired_at = ?3 WHERE owner_id = ?1 AND id = ?2",
                (self.owner.as_str(), old.to_string(), now),
            )?;
            Ok(())
        })
    }

    /// Deletes retired controlroom keys no machine authenticates with anymore; returns how
    /// many.
    pub fn prune_retired(&self) -> StoreResult<usize> {
        Ok(self.store.lock().execute(
            "DELETE FROM keys WHERE owner_id = ?1 AND kind = 'controlroom'
               AND retired_at IS NOT NULL
               AND id NOT IN (SELECT auth_key_id FROM machines
                              WHERE owner_id = ?1 AND auth_key_id IS NOT NULL)",
            [self.owner.as_str()],
        )?)
    }

    /// Deletes an additional key. Fails with a constraint error while a machine uses it.
    pub fn delete(&self, id: KeyId) -> StoreResult<bool> {
        let n = self.store.lock().execute(
            "DELETE FROM keys WHERE owner_id = ?1 AND id = ?2 AND kind = 'additional'",
            (self.owner.as_str(), id.to_string()),
        )?;
        Ok(n > 0)
    }
}
